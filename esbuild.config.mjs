import process from "node:process";
import esbuild from "esbuild";

// Kept at the top of the bundled main.js so that the notice and the location
// of the source travel with the distributed file.
const banner = `/*
 * Sync Evo
 * Copyright (C) 2026 seking
 *
 * This program is free software licensed under the GNU Affero General Public
 * License, version 3. It comes with ABSOLUTELY NO WARRANTY. See the LICENSE
 * file in the source repository for the full text.
 *
 * This file is generated by esbuild. The source is at:
 * https://github.com/seking/obsidian-sync-evo
 */
`;

const production = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	// Provided by the app at run time. Node builtins are left out on purpose:
	// the mobile app has no Node, so importing one from src/ must fail the build.
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	// Whitespace and syntax only; identifiers stay readable.
	minifyWhitespace: production,
	minifySyntax: production,
	legalComments: "inline",
	outfile: "main.js",
});

if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
